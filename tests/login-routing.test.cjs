const fs=require('node:fs');
const assert=require('node:assert/strict');
const home=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.html','utf8');
const signin=fs.readFileSync('signin.html','utf8');
const dashboard=fs.readFileSync('dashboard.html','utf8');
const pos=fs.readFileSync('pos.html','utf8');
const pages=fs.readFileSync('washpilot-pages.js','utf8');
const config=JSON.parse(fs.readFileSync('vercel.json','utf8'));
const signinLinks=home.split('href="/signin"').length-1;
assert.ok(signinLinks>=2,'Desktop and mobile homepage navigation should both use /signin.');
assert.ok(!home.includes('href="/login"'),'Homepage must not send sign-in clicks to /login.');
const redirect=(source,destination)=>config.redirects.some(x=>x.source===source&&x.destination===destination);
const rewrite=(source,destination)=>config.rewrites.some(x=>x.source===source&&x.destination===destination);
assert.ok(redirect('/signin.html','/signin'),'Legacy sign-in page should redirect to the integrated sign-in.');
assert.ok(redirect('/login','/signin'),'Old /login URL should redirect to the canonical /signin route.');
assert.ok(redirect('/dashboard.html','/dashboard'),'Standalone dashboard should redirect to the integrated dashboard.');
assert.ok(redirect('/pos.html','/new-wash'),'Standalone POS should redirect to the integrated POS.');
assert.ok(redirect('/pos','/new-wash'),'Old POS alias should redirect to the integrated POS.');
assert.ok(redirect('/home.html','/'),'Old duplicate homepage should redirect to the uploaded root homepage.');
assert.ok(redirect('/app.html','/'),'The preserved app entry must not be exposed as a second homepage.');
assert.ok(rewrite('/signin','/app.html'),'Canonical /signin should load the integrated application.');
assert.ok(rewrite('/dashboard','/app.html'),'Canonical /dashboard should load the integrated application.');
assert.ok(dashboard.includes('posUrl: "/new-wash"'),'Dashboard POS link must open the integrated POS route.');
assert.ok(pos.includes('dashboardUrl: "/dashboard"'),'POS dashboard link must open the integrated dashboard route.');
assert.ok(pages.includes(": '/dashboard';"),'Authenticated users must be sent to the integrated dashboard.');
assert.ok(!pages.includes("'/dashboard.html'"),'Shared page helper must not route users to the standalone dashboard.');
assert.equal((app.match(/data-page="dashboard"/g)||[]).length,1,'Integrated app must have only one dashboard nav item.');
assert.equal((app.match(/data-page="newwash"/g)||[]).length,1,'Integrated app must have only one POS nav item.');
assert.ok(app.includes("if(path==='/login'||path==='/signin'){"),'Integrated app must keep its /signin route.');
assert.ok(signin.includes('successUrl: "/dashboard"'),'Sign-in success must open the integrated dashboard.');
console.log('PASS: one integrated Dashboard and POS, legacy page redirects, canonical sign-in and authenticated dashboard routing.');
