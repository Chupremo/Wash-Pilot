const fs=require('node:fs');
const assert=require('node:assert/strict');
const home=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.html','utf8');
const signin=fs.readFileSync('signin.html','utf8');
const dashboard=fs.readFileSync('dashboard.html','utf8');
const config=JSON.parse(fs.readFileSync('vercel.json','utf8'));
const signinLinks=home.split('href="/signin"').length-1;
assert.ok(signinLinks>=2,'Desktop and mobile homepage navigation should both use /signin.');
assert.ok(!home.includes('href="/login"'),'Homepage must not send sign-in clicks to /login.');
assert.ok(config.redirects.some(x=>x.source==='/signin.html'&&x.destination==='/signin'),'Legacy sign-in page should redirect to /signin.');
assert.ok(config.redirects.some(x=>x.source==='/login'&&x.destination==='/signin'),'Old /login URL should redirect to the canonical /signin route.');
assert.ok(config.redirects.some(x=>x.source==='/dashboard.html'&&x.destination==='/dashboard'),'Legacy dashboard URL should redirect to the integrated dashboard.');
assert.ok(config.rewrites.some(x=>x.source==='/signin'&&x.destination==='/app.html'),'Canonical /signin should load the integrated application.');
assert.ok(config.rewrites.some(x=>x.source==='/dashboard'&&x.destination==='/app.html'),'Canonical /dashboard should load the integrated application.');
assert.ok(app.includes("window.wpRouteIsLogin=['/login','/signin'].includes(normalize(location.pathname));"),'Integrated app must identify /signin as a login route.');
assert.ok(app.includes("initialPath==='/signin'"),'Auth bootstrap must restore sessions on /signin.');
assert.ok(app.includes("if(path==='/login'||path==='/signin'){"),'Integrated route controller must display the sign-in screen on /signin.');
assert.ok(app.includes("setPath('/signin',false);"),'Interactive sign-in entry must navigate to /signin.');
assert.ok(app.includes("'/contact','/login','/signin','/signup','/booking'"),'Client-side router must intercept the canonical /signin route.');
assert.ok(signin.includes('successUrl: "/dashboard"'),'Legacy sign-in success target should open the integrated dashboard.');
assert.ok(dashboard.includes('signinUrl: "/login"'),'Legacy dashboard sign-in link remains covered by the /login redirect.');
assert.ok(app.includes("'/dashboard':'dashboard'"),'Requested dashboard route must select the integrated dashboard.');
console.log('PASS: homepage /signin links, canonical sign-in route, compatibility redirects and dashboard routing.');
